#!/usr/bin/env bash
# Install or verify the third-party agent skills used to develop MORN1NGST4R.
#
#   scripts/sync-agent-skills.sh install [source...]
#                                          fetch pinned upstream sources and (re)install managed skills.
#                                          Sources: superpowers caveman taste ui-ux-pro-max karpathy. Default: all.
#   scripts/sync-agent-skills.sh verify    check installed skills against .kiro/skills-lock.json (offline)
#
# Upstream content is copied unmodified. Only the directories listed below are
# managed; any other skill under .kiro/skills/ is left alone. To update an
# upstream, change its pin below, review the upstream diff, run `install`, and
# commit the result. See docs/development/agent-skills.md.
#
# Requires: bash, git, sha256sum, find, sort. `install` also needs network access,
# and npm/node for UI/UX Pro Max. Nothing here runs upstream install scripts
# except the pinned ui-ux-pro-max-cli package (`init --ai kiro --offline`).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SKILLS_DIR="$ROOT/.kiro/skills"
STEERING_DIR="$ROOT/.kiro/steering"
LICENSE_DIR="$ROOT/docs/development/third-party-licenses"
LOCK_FILE="$ROOT/.kiro/skills-lock.json"

# ---- Pins -----------------------------------------------------------------
SUPERPOWERS_REPO="https://github.com/obra/superpowers.git"
SUPERPOWERS_SHA="22f0b463e7a5e579904dd6211a520321035526f7"
# diagnosing-superpowers is intentionally excluded: it reads session logs and files GitHub issues.
SUPERPOWERS_SKILLS=(
  using-superpowers brainstorming writing-plans executing-plans
  test-driven-development systematic-debugging verification-before-completion
  requesting-code-review receiving-code-review finishing-a-development-branch
  subagent-driven-development dispatching-parallel-agents using-git-worktrees
  writing-skills
)

CAVEMAN_REPO="https://github.com/JuliusBrussee/caveman.git"
CAVEMAN_SHA="b4ee71d557d96e3cbc14f88fa6e953a1362865f5"

UIPRO_REPO="https://github.com/nextlevelbuilder/ui-ux-pro-max-skill.git"
UIPRO_SHA="6ae86f61f520d6ca229d2f40e070410638c908c5"
UIPRO_NPM_PACKAGE="ui-ux-pro-max-cli"
UIPRO_NPM_VERSION="2.15.0"
UIPRO_NPM_INTEGRITY="sha512-D0J/C40xrzzi5si6ZLtRGbEE5v3QjL7d4wJNnasmP3yfDSrGiuqVCdwQiqCNnIkbqOuVoA/uonR2o1WKXh3urw=="
# brand, design, slides, banner-design are excluded: logo/CIP/slide generators that need GEMINI_API_KEY
# and overlap with the art-direction role of design-taste-frontend.
UIPRO_SKILLS=(ui-ux-pro-max ui-styling design-system)

TASTE_REPO="https://github.com/Leonxlnx/taste-skill.git"
TASTE_SHA="f6b76575f949707b4e3c37cd86cb44b0b98643e8"
TASTE_UPSTREAM_DIR="skills/taste-skill"
TASTE_INSTALL_NAME="design-taste-frontend" # must equal the `name:` in its SKILL.md

# Kiro adapters exist only as open, unmerged upstream PRs (#114, #129). The upstream
# skill is already in Agent Skills format, so it is copied unmodified from main.
KARPATHY_REPO="https://github.com/multica-ai/andrej-karpathy-skills.git"
KARPATHY_SHA="2c606141936f1eeef17fa3043a72095b4765b9c2"

MANAGED_SKILLS=("${SUPERPOWERS_SKILLS[@]}" caveman "${UIPRO_SKILLS[@]}" "$TASTE_INSTALL_NAME" karpathy-guidelines)

die() { echo "error: $*" >&2; exit 1; }

tree_hash() { # deterministic content + mode hash of a directory
  (cd "$1" && find . -type f -print0 | LC_ALL=C sort -z \
    | xargs -0 sha256sum | sha256sum | cut -d' ' -f1)
}

fetch_pinned() { # repo sha dest
  git init -q "$3"
  git -C "$3" fetch -q --depth 1 "$1" "$2"
  git -C "$3" checkout -q FETCH_HEAD
  [[ "$(git -C "$3" rev-parse HEAD)" == "$2" ]] || die "pin mismatch for $1"
}

install_skill() { # source-dir install-name
  local src="$1" name="$2"
  [[ -n "$name" && "$name" != */* && "$name" != .* ]] || die "unsafe skill name: $name"
  [[ -f "$src/SKILL.md" ]] || die "no SKILL.md in $src"
  mkdir -p "$SKILLS_DIR"
  rm -rf "${SKILLS_DIR:?}/$name"
  cp -a "$src" "$SKILLS_DIR/$name"
}

write_caveman_steering() { # path-to-caveman-activate.md
  mkdir -p "$STEERING_DIR"
  {
    printf -- '---\ninclusion: always\n---\n\n'
    printf '<!-- Generated by scripts/sync-agent-skills.sh from %s@%s:src/rules/caveman-activate.md. Do not edit. -->\n\n' \
      "JuliusBrussee/caveman" "$CAVEMAN_SHA"
    cat "$1"
  } > "$STEERING_DIR/caveman.md"
}

write_lock() {
  local tmp_lock="$1"; shift
  {
    echo '{'
    echo '  "generatedBy": "scripts/sync-agent-skills.sh",'
    echo '  "sources": {'
    echo "    \"superpowers\": {\"repo\": \"${SUPERPOWERS_REPO%.git}\", \"commit\": \"$SUPERPOWERS_SHA\"},"
    echo "    \"caveman\": {\"repo\": \"${CAVEMAN_REPO%.git}\", \"commit\": \"$CAVEMAN_SHA\"},"
    echo "    \"ui-ux-pro-max\": {\"repo\": \"${UIPRO_REPO%.git}\", \"repoCommit\": \"$UIPRO_SHA\", \"installer\": \"$UIPRO_NPM_PACKAGE@$UIPRO_NPM_VERSION\", \"integrity\": \"$UIPRO_NPM_INTEGRITY\"},"
    echo "    \"taste\": {\"repo\": \"${TASTE_REPO%.git}\", \"commit\": \"$TASTE_SHA\", \"upstreamPath\": \"$TASTE_UPSTREAM_DIR\"},"
    echo "    \"karpathy-guidelines\": {\"repo\": \"${KARPATHY_REPO%.git}\", \"commit\": \"$KARPATHY_SHA\"}"
    echo '  },'
    echo '  "skills": {'
    local first=1 s
    for s in "${MANAGED_SKILLS[@]}"; do
      [[ $first -eq 1 ]] || echo ','
      first=0
      printf '    "%s": "%s"' "$s" "$(tree_hash "$SKILLS_DIR/$s")"
    done
    echo
    echo '  },'
    echo "  \"steering\": {\"caveman.md\": \"$(sha256sum "$STEERING_DIR/caveman.md" | cut -d' ' -f1)\"}"
    echo '}'
  } > "$tmp_lock"
}

cmd_install() {
  command -v git >/dev/null || die "git is required"
  command -v npx >/dev/null || die "npx (Node.js) is required for UI/UX Pro Max"
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' EXIT
  # Optional source filter: `install karpathy`. Default installs every source.
  only=" ${*:-all} "
  sel() { [[ "$only" == *" all "* || "$only" == *" $1 "* ]]; }
  local s

  if sel superpowers; then
    echo "==> superpowers @ ${SUPERPOWERS_SHA:0:7}"
    fetch_pinned "$SUPERPOWERS_REPO" "$SUPERPOWERS_SHA" "$work/superpowers"
    for s in "${SUPERPOWERS_SKILLS[@]}"; do install_skill "$work/superpowers/skills/$s" "$s"; done
    mkdir -p "$LICENSE_DIR"
    cp "$work/superpowers/LICENSE" "$LICENSE_DIR/superpowers.MIT.txt"
  fi

  if sel caveman; then
    echo "==> caveman @ ${CAVEMAN_SHA:0:7}"
    fetch_pinned "$CAVEMAN_REPO" "$CAVEMAN_SHA" "$work/caveman"
    install_skill "$work/caveman/skills/caveman" caveman
    write_caveman_steering "$work/caveman/src/rules/caveman-activate.md"
    mkdir -p "$LICENSE_DIR"
    cp "$work/caveman/LICENSE"     "$LICENSE_DIR/caveman.Apache-2.0.txt"
    cp "$work/caveman/NOTICE"      "$LICENSE_DIR/caveman.NOTICE.txt"
    cp "$work/caveman/LICENSE-MIT" "$LICENSE_DIR/caveman.MIT-pre-3.0.txt"
  fi

  if sel taste; then
    echo "==> taste @ ${TASTE_SHA:0:7}"
    fetch_pinned "$TASTE_REPO" "$TASTE_SHA" "$work/taste"
    install_skill "$work/taste/$TASTE_UPSTREAM_DIR" "$TASTE_INSTALL_NAME"
    mkdir -p "$LICENSE_DIR"
    cp "$work/taste/LICENSE" "$LICENSE_DIR/taste-skill.MIT.txt"
  fi

  if sel ui-ux-pro-max; then
    echo "==> ui-ux-pro-max ($UIPRO_NPM_PACKAGE@$UIPRO_NPM_VERSION, official Kiro installer)"
    local actual_integrity
    actual_integrity="$(npm view "$UIPRO_NPM_PACKAGE@$UIPRO_NPM_VERSION" dist.integrity)"
    [[ "$actual_integrity" == "$UIPRO_NPM_INTEGRITY" ]] || die "npm integrity mismatch for $UIPRO_NPM_PACKAGE"
    mkdir -p "$work/uipro"
    (cd "$work/uipro" && npx --yes "$UIPRO_NPM_PACKAGE@$UIPRO_NPM_VERSION" init --ai kiro --offline >/dev/null)
    # The installer targets .kiro/steering/<skill>/. Kiro loads on-demand skills from .kiro/skills/.
    for s in "${UIPRO_SKILLS[@]}"; do install_skill "$work/uipro/.kiro/steering/$s" "$s"; done
    fetch_pinned "$UIPRO_REPO" "$UIPRO_SHA" "$work/uipro-src"
    mkdir -p "$LICENSE_DIR"
    cp "$work/uipro-src/LICENSE" "$LICENSE_DIR/ui-ux-pro-max.MIT.txt"
    # ui-styling ships its own Apache-2.0 LICENSE.txt. Preserve it verbatim, since the payload is git-ignored.
    cp "$work/uipro/.kiro/steering/ui-styling/LICENSE.txt" "$LICENSE_DIR/ui-styling.bundled-LICENSE.txt"
  fi

  if sel karpathy; then
    echo "==> karpathy-guidelines @ ${KARPATHY_SHA:0:7}"
    fetch_pinned "$KARPATHY_REPO" "$KARPATHY_SHA" "$work/karpathy"
    install_skill "$work/karpathy/skills/karpathy-guidelines" karpathy-guidelines
    # Upstream ships no LICENSE file. License is declared as MIT in SKILL.md, plugin.json and README.
    mkdir -p "$LICENSE_DIR"
    {
      echo "karpathy-guidelines: upstream repository has no LICENSE file."
      echo "MIT is declared in skills/karpathy-guidelines/SKILL.md (license: MIT), .claude-plugin/plugin.json and README.md."
      echo "Source: ${KARPATHY_REPO%.git} @ $KARPATHY_SHA"
    } > "$LICENSE_DIR/karpathy-guidelines.NOTICE.txt"
  fi

  write_lock "$LOCK_FILE"
  echo "==> wrote ${LOCK_FILE#"$ROOT"/}"
  cmd_verify
}

cmd_verify() {
  [[ -f "$LOCK_FILE" ]] || die "missing $LOCK_FILE; run install"
  local bad=0 s want got
  for s in "${MANAGED_SKILLS[@]}"; do
    [[ -d "$SKILLS_DIR/$s" ]] || { echo "MISSING  $s"; bad=1; continue; }
    want="$(grep -E "^    \"$s\": \"[0-9a-f]{64}\"" "$LOCK_FILE" | sed -E 's/.*: "([0-9a-f]+)".*/\1/')"
    got="$(tree_hash "$SKILLS_DIR/$s")"
    if [[ "$want" == "$got" ]]; then echo "ok       $s"; else echo "MODIFIED $s"; bad=1; fi
  done
  want="$(grep -o '"caveman.md": "[0-9a-f]*"' "$LOCK_FILE" | sed -E 's/.*: "([0-9a-f]+)"/\1/')"
  got="$(sha256sum "$STEERING_DIR/caveman.md" | cut -d' ' -f1)"
  if [[ "$want" == "$got" ]]; then echo "ok       steering/caveman.md"; else echo "MODIFIED steering/caveman.md"; bad=1; fi
  return $bad
}

case "${1:-}" in
  install) shift; cmd_install "$@" ;;
  verify)  cmd_verify ;;
  *) sed -n '2,10p' "${BASH_SOURCE[0]}"; exit 2 ;;
esac
