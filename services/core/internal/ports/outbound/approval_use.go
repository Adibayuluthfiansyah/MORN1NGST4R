package outbound

import (
	"context"
	"errors"

	"github.com/Adibayuluthfiansyah/MORN1NGST4R/services/core/internal/domain/approval"
	"github.com/Adibayuluthfiansyah/MORN1NGST4R/services/core/internal/domain/operation"
)

// ErrRecoveryGeneration is returned when a claim or a launch check names a
// recovery generation that is not the current one, or when the database is not
// in the normal state (CC-15, docs/design/database/recovery-generation.md). The
// caller must stop claiming and let the recovery procedure run.
var ErrRecoveryGeneration = errors.New("recovery generation does not match or the database is not normal")

// ApprovalClaim asks to consume one use of an approval for a job (E2).
type ApprovalClaim struct {
	// UseID is the identifier for the approval_uses row, generated by the
	// application. It is ignored when the job already holds a use.
	UseID      string
	ApprovalID string
	JobID      string
	// ClaimEpoch is the job's claim epoch (at least 1).
	ClaimEpoch int
	// Generation is the recovery generation that the caller read from the marker.
	Generation uint64
	// Binding is the scope version, validation and policy snapshot in force now.
	Binding approval.Binding
	// Operation is the hash of the operation the job is about to run.
	Operation operation.Hash
}

// ClaimOutcome tells whether a claim consumed a use or found one.
type ClaimOutcome int

const (
	// ClaimConsumed: this claim consumed a use.
	ClaimConsumed ClaimOutcome = iota + 1
	// ClaimReused: the job already held a use, and the claim returned that
	// record without consuming another (a retry claim, or the losing side of a
	// concurrent claim for the same job).
	ClaimReused
)

// ClaimResult is the result of a successful claim.
type ClaimResult struct {
	Outcome ClaimOutcome
	// UseID identifies the approval_uses row of the job.
	UseID string
}

// LaunchCheck asks whether a job may launch now (E3). It consumes nothing.
type LaunchCheck struct {
	ApprovalID string
	JobID      string
	Generation uint64
	Binding    approval.Binding
	Operation  operation.Hash
}

// ApprovalUses consumes approval uses atomically in the database (TD-M2-05, M3
// part). The conditional update of the counter and the insert of the use are
// one transaction, so a use is never consumed twice and never beyond the
// approved maximum, whatever the number of concurrent claimers.
//
// A refusal is returned as an error that matches approval.ErrDenied and carries
// a stable approval.Reason (errors.As to *approval.DenialError). A recovery
// generation problem is ErrRecoveryGeneration. Any other error is a failure of
// the store, and the caller must treat it as a refusal.
//
// Inside a Transactor.InTx the operations join the transaction of the context,
// so a claim and the job update that records it commit or roll back together.
type ApprovalUses interface {
	Claim(ctx context.Context, c ApprovalClaim) (ClaimResult, error)
	CheckLaunch(ctx context.Context, c LaunchCheck) error
}
